/**
 * Prerenders the landing page in every language so search engines can index
 * each one. The sources stay docs/index.html (English, the template) and
 * docs/i18n/<lang>.json; this writes:
 *
 * - docs/<lang>/index.html for every translation,
 * - the language list and hreflang alternates inside docs/index.html,
 * - docs/sitemap.xml (every language plus any other docs/<path>/index.html
 *   page, picked up automatically) and docs/robots.txt.
 *
 * Download links and the version come from the template, so a release only
 * touches docs/index.html. Run with `bun run build:site`; CI fails if the
 * committed output is stale.
 */
import { readdir, rm } from "node:fs/promises";

/** Where the site is served. Changing it and rebuilding moves every absolute
 * URL: canonical, Open Graph, structured data, hreflang, sitemap and robots. */
const SITE = "https://chatpane.app/";

type Locale = { rtl: boolean; t: Record<string, string | string[]> };

const docs = new URL("../../docs/", import.meta.url);
const file = (path: string) => new URL(path, docs);
const GENERATED = "<!-- GENERATED by scripts/site/build.ts";

let template = await Bun.file(file("index.html")).text();

const previousSite = template.match(/<link rel="canonical" href="([^"]+)">/)?.[1];
// Translations link downloads as `{download}mac_arm.dmg`; this takes the base
// (repository, tag and asset prefix) from the English page, which the release
// workflow rewrites, so a new release or asset name never touches them.
const download = template.match(
  /https:\/\/github\.com\/[^"']+\/releases\/download\/v\d+\.\d+\.\d+\/[^"'/]+?_\d+\.\d+\.\d+_/,
)?.[0];
const version = template.match(/\/releases\/download\/v(\d+\.\d+\.\d+)\//)?.[1];
const signedChecks = template.match(/var I18N_SIGNED_UPDATE_CHECKS = (\{[\s\S]*?\});/)?.[1];
if (!previousSite || !SITE.endsWith("/") || !download || !version || !signedChecks) {
  throw new Error("docs/index.html lost its canonical URL, release links or signed-check phrases");
}
const site = SITE;
template = template.replaceAll(previousSite, site);
const signedCheckPhrases = JSON.parse(signedChecks) as Record<string, string>;

const langs = (await readdir(file("i18n")))
  .filter((name) => name.endsWith(".json"))
  .map((name) => name.slice(0, -".json".length))
  .sort();
const allLangs = ["en", ...langs];
const pageUrl = (lang: string) => (lang === "en" ? site : `${site}${lang}/`);

// 1. The template's own generated parts: the language list and alternates.
const alternates = [...allLangs, "x-default"]
  .map((lang) => {
    const href = pageUrl(lang === "x-default" ? "en" : lang);
    return `<link rel="alternate" hreflang="${lang}" href="${href}">`;
  })
  .join("\n");
template = replaceOnce(
  template,
  /(<!-- i18n-alternates[^>]*-->\n)[\s\S]*?(<!-- \/i18n-alternates -->)/,
  (_, open: string, close: string) => `${open}${alternates}\n${close}`,
);
template = replaceOnce(
  template,
  /var I18N_LOCALES = \[[^\]]*\];/,
  () => `var I18N_LOCALES = ${JSON.stringify(allLangs).replaceAll(",", ", ")};`,
);
await writeIfChanged("index.html", template);

// 2. One prerendered page per translation.
for (const lang of langs) {
  if (!template.includes(`<option value="${lang}">`)) {
    throw new Error(`The language menu in docs/index.html has no option for ${lang}`);
  }
  const raw = await Bun.file(file(`i18n/${lang}.json`)).text();
  const locale = JSON.parse(
    raw.replaceAll("{download}", download).replaceAll("{version}", version),
  ) as Locale;
  // Every translation must say the update *check* is signed (see the template).
  const trust = text(locale, "dl.trust");
  const signed = signedCheckPhrases[lang];
  if (!signed) throw new Error(`I18N_SIGNED_UPDATE_CHECKS has no phrase for ${lang}`);
  locale.t["dl.trust"] = trust.slice(0, trust.lastIndexOf(" · ") + 3) + signed;

  await writeIfChanged(`${lang}/index.html`, renderPage(lang, locale));
}

// Remove pages for languages whose translation file is gone.
for await (const path of new Bun.Glob("*/index.html").scan(docs.pathname)) {
  const dir = path.split("/")[0]!;
  if (allLangs.includes(dir)) continue;
  if ((await Bun.file(file(path)).text()).includes(GENERATED)) {
    await rm(file(`${dir}/`), { recursive: true });
    console.log(`removed docs/${dir}/`);
  }
}

// 3. Sitemap and robots.txt. Other pages (docs/<path>/index.html written by
// hand) join the sitemap automatically.
const extraPages: string[] = [];
for await (const path of new Bun.Glob("**/index.html").scan(docs.pathname)) {
  const dir = path.slice(0, -"index.html".length);
  if (dir === "" || allLangs.includes(dir.slice(0, -1))) continue;
  extraPages.push(`${site}${dir}`);
}
extraPages.sort();

const links = allLangs
  .concat("x-default")
  .map((lang) => {
    const href = pageUrl(lang === "x-default" ? "en" : lang);
    return `    <xhtml:link rel="alternate" hreflang="${lang}" href="${href}"/>`;
  })
  .join("\n");
const urls = [
  ...allLangs.map((lang) => `  <url>\n    <loc>${pageUrl(lang)}</loc>\n${links}\n  </url>`),
  ...extraPages.map((url) => `  <url>\n    <loc>${url}</loc>\n  </url>`),
];
await writeIfChanged(
  "sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join("\n")}
</urlset>
`,
);
// Crawlers only read robots.txt at the host root, so this takes effect once
// the site is served from its own domain.
await writeIfChanged("robots.txt", `User-agent: *\nAllow: /\n\nSitemap: ${site}sitemap.xml\n`);

function renderPage(lang: string, locale: Locale): string {
  const title = text(locale, "meta.title");
  const desc = text(locale, "meta.desc");
  const url = pageUrl(lang);
  const payload = JSON.stringify({ [lang]: locale }).replaceAll("</", "<\\/");

  let html = replaceOnce(
    template,
    /var I18N = \/\*__I18N_LOCALES__\*\/ \{.*\};\n/,
    () => `var I18N = /*__I18N_LOCALES__*/ ${payload};\n`,
  );
  html = html.replaceAll("url(avatars/en/", `url(../avatars/${lang}/`);
  html = html.replace(
    "<!DOCTYPE html>\n",
    `<!DOCTYPE html>\n${GENERATED} from index.html and i18n/${lang}.json. Do not edit. -->\n`,
  );

  const content = (value: string) => ({
    element(el: HTMLRewriterTypes.Element) {
      el.setAttribute("content", value);
    },
  });
  const translate = (attr: string, target: string) => ({
    element(el: HTMLRewriterTypes.Element) {
      el.setAttribute(target, text(locale, el.getAttribute(attr)!));
    },
  });
  // Asset paths are relative to the site root; this page sits one level down.
  const relocate = (attr: string) => ({
    element(el: HTMLRewriterTypes.Element) {
      const value = el.getAttribute(attr)!;
      if (/^(?:[a-z][a-z0-9+.-]*:|\/|#)/i.test(value)) return;
      el.setAttribute(attr, `../${value.replace(/^\.\//, "")}`);
    },
  });

  return new HTMLRewriter()
    .on("html", {
      element(el) {
        el.setAttribute("lang", lang);
        if (locale.rtl) el.setAttribute("dir", "rtl");
      },
    })
    .on("title", {
      element(el) {
        el.setInnerContent(title);
      },
    })
    .on('meta[name="description"]', content(desc))
    .on('meta[property="og:title"]', content(title))
    .on('meta[property="og:description"]', content(desc))
    .on('meta[name="twitter:title"]', content(title))
    .on('meta[name="twitter:description"]', content(desc))
    .on('meta[property="og:url"]', content(url))
    .on('link[rel="canonical"]', {
      element(el) {
        el.setAttribute("href", url);
      },
    })
    .on("[data-i18n]", {
      element(el) {
        const value = text(locale, el.getAttribute("data-i18n")!);
        if (value === "") return;
        el.setInnerContent(value, { html: el.hasAttribute("data-i18n-html") });
      },
    })
    .on("[data-i18n-aria]", translate("data-i18n-aria", "aria-label"))
    .on("[data-i18n-alt]", translate("data-i18n-alt", "alt"))
    .on(`#langSel option[value="${lang}"]`, {
      element(el) {
        el.setAttribute("selected", "");
      },
    })
    .on("[src]", relocate("src"))
    .on("[href]", relocate("href"))
    .transform(html);
}

function text(locale: Locale, key: string): string {
  const value = locale.t[key];
  if (typeof value !== "string") throw new Error(`Translation is missing the text key ${key}`);
  return value;
}

function replaceOnce(
  source: string,
  pattern: RegExp,
  replacement: (match: string, ...groups: string[]) => string,
): string {
  if (!pattern.test(source)) throw new Error(`docs/index.html no longer matches ${pattern}`);
  return source.replace(pattern, replacement);
}

async function writeIfChanged(path: string, contents: string) {
  const target = Bun.file(file(path));
  if ((await target.exists()) && (await target.text()) === contents) return;
  await Bun.write(target, contents);
  console.log(`wrote docs/${path}`);
}
